#!/usr/bin/env node
// Build the @typographics-art/keys npm package from keys/registry.json: copy the registry in and (re)generate index.js
// with the registry embedded, so the package needs no file read and works in Node, bundlers and browsers alike. Run it
// whenever the registry changes (after `tg keys build`/`add`), then publish:  cd packages/keys && npm publish --access public
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PKG = join(ROOT, 'packages', 'keys');
const registry = JSON.parse(readFileSync(join(ROOT, 'keys', 'registry.json'), 'utf8'));
mkdirSync(PKG, { recursive: true });

writeFileSync(join(PKG, 'registry.json'), JSON.stringify(registry, null, 2) + '\n');
writeFileSync(join(PKG, 'index.js'), `// @typographics-art/keys — GENERATED by scripts/build-keys-package.mjs from keys/registry.json. Do not edit by hand.
// The verified Typographics Art issuer keys, embedded so this works in Node, bundlers and browsers without reading a file.
export const registry = ${JSON.stringify(registry, null, 2)};
export const issuers = () => registry.issuers.map((e) => e.issuer);
export const getIssuer = (domain) => registry.issuers.find((e) => e.issuer === domain) || null;
export default registry;
`);

const pkg = JSON.parse(readFileSync(join(PKG, 'package.json'), 'utf8'));
console.log(`built packages/keys/ (${pkg.name}@${pkg.version}) from keys/registry.json — ${registry.issuers.length} issuer(s): ${registry.issuers.map((e) => e.issuer).join(', ')}`);
console.log('publish (operator): cd packages/keys && npm publish --access public   # bump the version first; versions are immutable');
