#!/usr/bin/env node
// Build the key-registry packages from keys/registry.json: the npm package (@typographics-art/keys) and the PyPI package
// (tgart-keys), so agents that can reach npm OR PyPI — but not an arbitrary website — can verify signed Typograms. Both
// just carry the registry as data (immutable per published version). Run after the registry changes (`tg keys build`/`add`).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(readFileSync(join(ROOT, 'keys', 'registry.json'), 'utf8'));
const json = JSON.stringify(registry, null, 2) + '\n';

// npm: @typographics-art/keys — registry.json plus index.js with the registry embedded (no file read; works everywhere).
const NPM = join(ROOT, 'packages', 'keys');
mkdirSync(NPM, { recursive: true });
writeFileSync(join(NPM, 'registry.json'), json);
writeFileSync(join(NPM, 'index.js'), `// @typographics-art/keys — GENERATED by scripts/build-keys-package.mjs from keys/registry.json. Do not edit by hand.
// The verified Typographics Art issuer keys, embedded so this works in Node, bundlers and browsers without reading a file.
export const registry = ${JSON.stringify(registry, null, 2)};
export const issuers = () => registry.issuers.map((e) => e.issuer);
export const getIssuer = (domain) => registry.issuers.find((e) => e.issuer === domain) || null;
export default registry;
`);

// PyPI: tgart-keys — the registry ships as package data; tgart_keys/__init__.py reads it.
const PYPI = join(ROOT, 'packages', 'pypi-keys', 'tgart_keys');
mkdirSync(PYPI, { recursive: true });
writeFileSync(join(PYPI, 'registry.json'), json);

const npmPkg = JSON.parse(readFileSync(join(NPM, 'package.json'), 'utf8'));
console.log(`built packages/keys/ (${npmPkg.name}@${npmPkg.version}) and packages/pypi-keys/ (tgart-keys) from keys/registry.json — ${registry.issuers.length} issuer(s): ${registry.issuers.map((e) => e.issuer).join(', ')}`);
console.log('publish (operator): cd packages/keys && npm publish --access public');
console.log('                    cd packages/pypi-keys && python3 -m build && twine upload dist/*');
console.log('(bump the version in each first — published versions are immutable)');
